package tg2086.util;

import javax.swing.*;
import javax.swing.table.TableModel;
import java.io.*;
import java.text.SimpleDateFormat;
import java.util.Date;

/**
 * AdminReportUtil - Report generator using Java Character Streams.
 * - Character Streams (BufferedWriter, FileWriter, PrintWriter)
 * - Safe file writing with try-with-resources
 * - CSV report formatting for administrative records
 */
public final class AdminReportUtil {

    private AdminReportUtil() {
        // Prevent instantiation
    }

    /**
     * Exports the data from a TableModel to a comma-separated values (CSV) file.
     *
     * @param model    the JTable's TableModel to export
     * @param reportTitle title written in the report header
     * @param destFile target destination file
     * @return true if export succeeded, false otherwise
     */
    public static boolean exportTableToCSV(TableModel model, String reportTitle, File destFile) {
        if (model == null || destFile == null) {
            return false;
        }

        try (PrintWriter writer = new PrintWriter(new BufferedWriter(new FileWriter(destFile)))) {
            // Write Header Metadata
            writer.println("# Faculty Technical Management System (FTMS) - Report");
            writer.println("# Report Title: " + reportTitle);
            writer.println("# Generated On: " + new SimpleDateFormat("yyyy-MM-dd HH:mm:ss").format(new Date()));
            writer.println("# Generated By: System Administrator (TG/2024/2086)");
            writer.println();

            // Write Column Headers
            int colCount = model.getColumnCount();
            StringBuilder headerLine = new StringBuilder();
            for (int i = 0; i < colCount; i++) {
                headerLine.append(escapeCSV(model.getColumnName(i)));
                if (i < colCount - 1) headerLine.append(",");
            }
            writer.println(headerLine.toString());

            // Write Rows
            int rowCount = model.getRowCount();
            for (int r = 0; r < rowCount; r++) {
                StringBuilder rowLine = new StringBuilder();
                for (int c = 0; c < colCount; c++) {
                    Object val = model.getValueAt(r, c);
                    rowLine.append(escapeCSV(val != null ? val.toString() : ""));
                    if (c < colCount - 1) rowLine.append(",");
                }
                writer.println(rowLine.toString());
            }

            writer.flush();
            return true;
        } catch (IOException ex) {
            ex.printStackTrace();
            return false;
        }
    }

    private static String escapeCSV(String value) {
        if (value == null) return "";
        if (value.contains(",") || value.contains("\"") || value.contains("\n")) {
            return "\"" + value.replace("\"", "\"\"") + "\"";
        }
        return value;
    }
}
